function buildTimeline(report) {
  const steps = STATUS_STEPS[report.status] || ['diterima'];
  const workDate = formatDateId(addDays(report.reportedDate, STEP_OFFSET.berlangsung));

  const content = {
    diterima: ['Laporan diterima', 'Warga mengirim laporan lengkap dengan foto dan titik lokasi.'],
    menungguVerifikasi: [
      'Menunggu verifikasi admin',
      'Admin akan memeriksa foto, lokasi, dan kategori laporan.',
    ],
    diverifikasi: [
      'Laporan diverifikasi',
      'Petugas memastikan lokasi dan tingkat kerusakan sesuai laporan.',
    ],
    menungguPrioritas: [
      'Menunggu penetapan prioritas',
      'Admin meninjau rekomendasi awal sebelum menetapkan prioritas.',
    ],
    prioritas: [
      `Prioritas ditetapkan ${report.priority}`,
      `Keputusan diverifikasi admin: ${report.decisionNote}`,
    ],
    penjadwalan: ['Menunggu penjadwalan perbaikan', 'Tim lapangan belum ditugaskan.'],
    dijadwalkan: ['Perbaikan dijadwalkan', `Tim lapangan dijadwalkan bekerja pada ${workDate}.`],
    berlangsung: ['Perbaikan berlangsung', 'Tim lapangan mengerjakan perbaikan di lokasi.'],
    konfirmasi: [
      'Menunggu konfirmasi warga',
      'Perbaikan selesai dikerjakan. Warga sekitar diminta memastikan hasilnya.',
    ],
    selesai: ['Laporan selesai', 'Warga mengonfirmasi hasil perbaikan sudah sesuai.'],
    ditinjau: ['Laporan ditinjau', 'Admin memeriksa kesesuaian laporan dengan data yang ada.'],
    ditutup: ['Laporan ditutup', report.closeReason || 'Laporan ditutup oleh admin.'],
  };

  return steps.map((key, idx) => ({
    key,
    title: content[key][0],
    note: content[key][1],
    date: formatDateId(addDays(report.reportedDate, STEP_OFFSET[key])),
    isCurrent: idx === steps.length - 1,
  }));
}

